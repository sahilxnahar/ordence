/**
 * The 500-feature platform catalogue.
 *
 * This is an opportunity inventory, not a shipped-feature list — items
 * 1–340 are horizontal capabilities every tenant's kernel can carry, and
 * 341–500 are industry-pack capabilities layered on the same kernel.
 *
 * It exists as typed data rather than CMS content for one reason: the
 * industry explorer on /features, the provisioning wizard in the admin
 * console and the activation sheet a customer signs should all be reading
 * the same list. Three copies of a 500-row catalogue would disagree within
 * a month.
 *
 * `pack: null` means horizontal — available to every industry. A pack name
 * means the capability only appears when that pack is licensed.
 */

export interface Feature {
  id: number;
  title: string;
  blurb: string;
  /** Category heading, e.g. "Opportunities and Pipeline". */
  group: string;
  /** Top-level division: "crm" | "erp" | "pack". */
  domain: "crm" | "erp" | "pack";
  /** Industry pack name, or null for horizontal capabilities. */
  pack: string | null;
}

type Row = [number, string, string];

function group(
  name: string,
  domain: Feature["domain"],
  pack: string | null,
  rows: Row[],
): Feature[] {
  return rows.map(([id, title, blurb]) => ({
    id,
    title,
    blurb,
    group: name,
    domain,
    pack,
  }));
}

