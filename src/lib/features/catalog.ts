/**
 * Packs that draw on a second pack's capabilities in practice. A real-estate
 * developer running their own sites needs the construction module; a
 * dealership needs field service. Modelled here rather than duplicating
 * rows, so the catalogue stays one row per capability.
 */
export const PACK_AFFINITY: Record<string, string[]> = {
  "Real Estate": ["Construction"],
  Construction: ["Real Estate"],
  Automotive: ["Retail and Ecommerce"],
  Manufacturing: ["Logistics"],
  Logistics: ["Manufacturing"],
};

export const DOMAIN_LABEL: Record<Feature["domain"], string> = {
  crm: "CRM, growth & service",
  erp: "ERP & enterprise operations",
  pack: "Industry pack",
};

/** Ordered category list for a domain, preserving catalogue order. */
export function groupsFor(features: Feature[]): string[] {
  const seen: string[] = [];
  for (const f of features) if (!seen.includes(f.group)) seen.push(f.group);
  return seen;
}

/**
 * What a given industry's workspace covers: every horizontal capability,
 * plus that pack, plus any affinity packs.
 */
export function featuresForIndustry(pack: string | null): Feature[] {
  if (!pack) return FEATURES.filter((f) => f.pack === null);
  const allowed = new Set([pack, ...(PACK_AFFINITY[pack] ?? [])]);
  return FEATURES.filter((f) => f.pack === null || allowed.has(f.pack));
}
